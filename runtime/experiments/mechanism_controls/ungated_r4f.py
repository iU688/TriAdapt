"""Parameter-matched reliability-blind control for the formal R4-F Self model.

The control retains the complete R4-F architecture, parameter tensors,
initialization, temporal repair branch, and optimizer-visible parameter count.
Its only functional change is inside the self-context adapter: the learned
person-level reliability gate is replaced by a learned sample-independent
scalar generated by the same six-input MLP.  This isolates whether conditioning
the adapter amplitude on the deterministic reliability cues is useful.
"""

from __future__ import annotations

import torch

from models.r4e_unified_graphmlp import (
    R4EUnifiedGraphMLP,
    ReliabilityContextAdapter,
)


class ReliabilityBlindContextAdapter(ReliabilityContextAdapter):
    """R4-F adapter whose same-sized gate does not read reliability.

    A zero six-vector is supplied to the unchanged gate MLP.  Consequently the
    gate is a learned global scalar (broadcast over batch and person), while all
    parameter names and shapes remain identical to the formal adapter.
    """

    def forward(
        self,
        features,
        reliability,
        anchors,
        pair_is_distinct,
        mode,
        residual_scale=1.0,
    ):
        if mode != "self":
            raise ValueError("the reliability-blind control is defined only for self context")
        if features.ndim != 4:
            raise ValueError("features must have shape (B,P,J,C)")
        if reliability.shape[:2] != features.shape[:2]:
            raise ValueError("reliability batch/person axes must match features")

        normalized = self.norm(features)
        geometry = self.relative_geometry(anchors, "self")
        query = self.query(normalized) + self.geometry(geometry).unsqueeze(2)
        key, value = self.key(normalized), self.value(normalized)
        attention = torch.softmax(
            torch.einsum("bpjd,bpkd->bpjk", query, key) / self.scale,
            dim=-1,
        )
        context = torch.einsum("bpjk,bpkd->bpjd", attention, value)

        # This is the sole functional change from ReliabilityContextAdapter:
        # neither the MLP input nor an outer multiplier depends on reliability.
        gate_input = torch.zeros(
            (*features.shape[:2], 6), dtype=features.dtype, device=features.device
        )
        gate = self.gate(gate_input).squeeze(-1)
        return (
            features
            + float(residual_scale) * gate[..., None, None] * self.output(context),
            gate,
        )


class R4FParameterMatchedUngatedGraphMLP(R4EUnifiedGraphMLP):
    """Formal R4-F Self with only its reliability-conditioned gate removed."""

    CONTROL_VARIANT = "self_reliability_blind"

    def __init__(self, args):
        # Construct the formal model first so every initialized tensor is exactly
        # the one obtained by the published R4-F constructor at the same RNG seed.
        super().__init__(args, "self")
        formal_state = {
            name: tensor.detach().clone() for name, tensor in self.adapter.state_dict().items()
        }
        cpu_rng = torch.random.get_rng_state()
        cuda_rng = torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None
        replacement = ReliabilityBlindContextAdapter(args.channel, args.adapter_dim)
        replacement.load_state_dict(formal_state, strict=True)
        self.adapter = replacement
        # Replacing a module must not consume RNG relative to formal R4-F.
        torch.random.set_rng_state(cpu_rng)
        if cuda_rng is not None:
            torch.cuda.set_rng_state_all(cuda_rng)
        # Keep the base-class dispatch label: R4EUnifiedGraphMLP.forward only
        # executes ``self.adapter`` for variant="self".  The distinct control
        # identity is stored in checkpoint metadata, never in this dispatcher.
        self.variant = "self"


def assert_exact_parameter_match(formal, control):
    """Raise if the formal and control models differ in names/shapes/values."""

    formal_state = formal.state_dict()
    control_state = control.state_dict()
    if set(formal_state) != set(control_state):
        missing = sorted(set(formal_state) - set(control_state))
        unexpected = sorted(set(control_state) - set(formal_state))
        raise AssertionError(f"state keys differ: missing={missing}, unexpected={unexpected}")
    for name in formal_state:
        left, right = formal_state[name], control_state[name]
        if left.shape != right.shape or not torch.equal(left, right):
            raise AssertionError(f"parameter/buffer initialization differs at {name}")
    formal_count = sum(parameter.numel() for parameter in formal.parameters())
    control_count = sum(parameter.numel() for parameter in control.parameters())
    if formal_count != control_count:
        raise AssertionError(f"parameter count differs: {formal_count} != {control_count}")
